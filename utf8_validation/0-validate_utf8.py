#!/usr/bin/python3

def validUTF8(data):
    for num in data:
        if num >= 256:
            return False
    return True


data = [65]
print(validUTF8(data))

data = [80, 121, 116, 104, 111, 110, 32, 105, 115, 32, 99, 111, 111, 108, 33]
print(validUTF8(data))

data = [229, 65, 127, 256]
print(validUTF8(data))
